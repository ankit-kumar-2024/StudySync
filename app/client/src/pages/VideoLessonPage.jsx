import React, { useState, useEffect, useMemo } from "react";
import { useSelector, useDispatch } from "react-redux";
import { useNavigate } from "react-router-dom";
import { Play, PlayCircle, Sparkles, Search, Bookmark } from "lucide-react";
import WatchingPage from "../components/video/WatchingPage";
import { setActiveVideoFromCourse } from "../store/slices/resourcesSlice";

export default function VideoLessonPage() {
  const dispatch = useDispatch();
  const navigate = useNavigate();

  const token = useSelector((state) => state.auth.token);
  const resources = useSelector((state) => state.resources.items);
  const activeVideoFromCourse = useSelector(
    (state) => state.resources.activeVideoFromCourse,
  );

  const [selectedVideo, setSelectedVideo] = useState(
    activeVideoFromCourse || null,
  );
  const [searchQuery, setSearchQuery] = useState("");
  const [savedIds, setSavedIds] = useState([]);

  useEffect(() => {
    if (activeVideoFromCourse) {
      setSelectedVideo(activeVideoFromCourse);
      dispatch(setActiveVideoFromCourse(null));
    }
  }, [activeVideoFromCourse, dispatch]);

  // Extract all video lectures generated by Sync AI courses
  const courseLectures = useMemo(() => {
    const vids = [];
    resources.forEach((r) => {
      if (r.courseData?.modules) {
        r.courseData.modules.forEach((m) => {
          if (m.video) {
            vids.push({
              ...m.video,
              category: r.title,
              courseId: r.id,
            });
          }
        });
      }
    });
    return vids;
  }, [resources]);

  const filteredLectures = courseLectures.filter((v) => {
    if (!searchQuery.trim()) return true;
    const q = searchQuery.toLowerCase();
    return (
      v.title?.toLowerCase().includes(q) ||
      v.category?.toLowerCase().includes(q)
    );
  });

  const handleDownloadGeneratedPdf = async (item) => {
    const res = await fetch(
      `http://localhost:5000/api/resources/course/${item.id}/pdf`,
      {
        headers: { Authorization: `Bearer ${token}` },
      },
    );
    if (res.ok) {
      const blob = await res.blob();
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `${item.title.replace(/\s+/g, "_")}.pdf`;
      a.click();
    }
  };

  const toggleSave = (id) => {
    setSavedIds((prev) =>
      prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id],
    );
  };

  // Identical WatchingPage UI used across BooksPage & VideoLessonPage
  if (selectedVideo) {
    const relatedPdfs = resources.filter(
      (r) => r.file_type?.toLowerCase() === "pdf",
    );
    const relatedBooks = resources.filter(
      (r) => r.file_type?.toLowerCase() === "book",
    );

    return (
      <WatchingPage
        video={selectedVideo}
        recommendedVideos={courseLectures}
        relatedPdfs={relatedPdfs}
        relatedBooks={relatedBooks}
        savedIds={savedIds}
        onToggleSave={toggleSave}
        onSelectVideo={(vid) => setSelectedVideo(vid)}
        onBack={() => setSelectedVideo(null)}
        backLabel="Back to Video Lessons"
        trackLabel={`Course Track • ${selectedVideo.category || "Video Lecture"}`}
        onDownloadCustomPdf={handleDownloadGeneratedPdf}
      />
    );
  }

  // Empty State when no video courses have been generated via Sync AI yet
  if (courseLectures.length === 0) {
    return (
      <div className="max-w-3xl mx-auto py-16 text-center space-y-4">
        <div className="w-14 h-14 rounded-2xl bg-cyan-500/15 border border-cyan-500/30 text-cyan-400 flex items-center justify-center mx-auto">
          <PlayCircle className="w-7 h-7" />
        </div>
        <h1 className="text-xl font-bold text-white">No Video Lectures Yet</h1>
        <p className="text-xs text-slate-400 max-w-md mx-auto leading-relaxed">
          Ask <strong>Sync AI</strong> to build a{" "}
          <strong>Complete Course</strong> with video lectures—your topic videos
          will appear here automatically.
        </p>
        <button
          type="button"
          onClick={() => navigate("/app/chat")}
          className="px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-bold inline-flex items-center gap-2 cursor-pointer"
        >
          <Sparkles className="w-4 h-4" /> Build Course with Video Lectures
        </button>
      </div>
    );
  }

  return (
    <div className="space-y-6 text-slate-100 pb-12">
      <div className="bg-[#0F1624] border border-slate-800 rounded-3xl p-6 flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <span className="inline-flex items-center gap-1.5 text-xs font-semibold text-cyan-400 mb-1">
            <PlayCircle className="w-3.5 h-3.5" /> Sync AI Curated Lectures
          </span>
          <h1 className="text-xl sm:text-2xl font-bold text-white">
            Course Video Lectures ({filteredLectures.length})
          </h1>
          <p className="text-xs text-slate-400 mt-0.5">
            Click any video lecture to open the unified watch workspace with
            paired PDF notes.
          </p>
        </div>

        <div className="relative w-full md:w-80">
          <Search className="w-4 h-4 text-slate-500 absolute left-3.5 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            placeholder="Filter video lectures..."
            className="w-full h-10 pl-10 pr-4 bg-[#070A11] border border-slate-800 rounded-xl text-xs text-white focus:outline-none focus:border-indigo-500"
          />
        </div>
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-5">
        {filteredLectures.map((video) => {
          const isSaved = savedIds.includes(video.id);
          return (
            <div
              key={`${video.courseId}-${video.id}`}
              onClick={() => setSelectedVideo(video)}
              className="group bg-[#0F1624] border border-slate-800 hover:border-cyan-500/50 rounded-2xl overflow-hidden cursor-pointer transition-all flex flex-col"
            >
              <div className="relative aspect-video bg-slate-900 overflow-hidden">
                <img
                  src={video.thumbnail}
                  alt={video.title}
                  className="w-full h-full object-cover group-hover:scale-105 transition duration-300"
                />
                <div className="absolute inset-0 bg-black/25 group-hover:bg-black/45 transition flex items-center justify-center">
                  <div className="w-11 h-11 rounded-full bg-cyan-500 text-slate-950 flex items-center justify-center shadow-lg">
                    <Play className="w-5 h-5 fill-slate-950 ml-0.5" />
                  </div>
                </div>
                <span className="absolute top-2.5 left-2.5 px-2.5 py-0.5 rounded-md bg-indigo-600/90 text-[10px] font-bold text-white truncate max-w-[75%]">
                  {video.category}
                </span>
              </div>

              <div className="p-4 flex-1 flex flex-col justify-between space-y-3">
                <div>
                  <h3 className="text-sm font-bold text-white line-clamp-2 group-hover:text-cyan-300">
                    {video.title}
                  </h3>
                  <p className="text-xs text-slate-400 mt-1">
                    {video.channelTitle}
                  </p>
                </div>

                <div className="pt-2.5 border-t border-slate-800 flex items-center justify-between text-[11px] text-slate-400">
                  <span>Watch with PDF Notes →</span>
                  <button
                    type="button"
                    onClick={(e) => {
                      e.stopPropagation();
                      toggleSave(video.id);
                    }}
                    className={`p-1 rounded-lg ${isSaved ? "text-cyan-400" : "hover:text-white"}`}
                  >
                    <Bookmark className="w-3.5 h-3.5" />
                  </button>
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
